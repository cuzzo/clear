use lineage::diff::{
    AddedLines, ChangeInventory, ConfigFile, DependencyChange, DependencyEntry, DependencyStatus,
    DiffFile, DiffGroup, DiffPlan, DiffScope, EvidenceAvailability, EvidenceScopeFingerprint,
    EvidenceState, FileChangeKind, LanguageSummary, LineAnnotation, LineVerification,
    ResolvedSarifFinding, RiskSummary, SarifFindingSummary, SourceRole,
    VerificationSlices, Visibility, VisibilityVerificationSlices,
};
use std::path::Path;
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output = Path::new(env!("CARGO_MANIFEST_DIR")).join("ui/src/generated/diff.ts");
    let declarations = [
        DiffPlan::decl(),
        DiffScope::decl(),
        EvidenceScopeFingerprint::decl(),
        ChangeInventory::decl(),
        ConfigFile::decl(),
        DiffFile::decl(),
        LineAnnotation::decl(),
        LineVerification::decl(),
        ResolvedSarifFinding::decl(),
        DiffGroup::decl(),
        SarifFindingSummary::decl(),
        AddedLines::decl(),
        VerificationSlices::decl(),
        RiskSummary::decl(),
        LanguageSummary::decl(),
        VisibilityVerificationSlices::decl(),
        EvidenceAvailability::decl(),
        DependencyChange::decl(),
        DependencyEntry::decl(),
        FileChangeKind::decl(),
        SourceRole::decl(),
        EvidenceState::decl(),
        Visibility::decl(),
        DependencyStatus::decl(),
    ]
    .join("\n\n")
    .replacen("type ", "export type ", 1)
    .replace("\ntype ", "\nexport type ")
    .lines()
    .map(str::trim_end)
    .collect::<Vec<_>>()
    .join("\n");
    std::fs::create_dir_all(output.parent().expect("generated parent"))?;
    std::fs::write(
        output,
        format!(
            "// Generated by cargo run --bin generate_diff_api. Do not edit.\n\n{declarations}\n"
        ),
    )?;
    Ok(())
}
